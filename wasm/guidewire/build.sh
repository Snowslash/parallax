#!/bin/sh
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
: "${CARGO_TARGET_DIR:?Set a fresh isolated Cargo target directory}"
: "${CARGO_HOME:?Set an isolated Cargo home (no shared configuration writes)}"
: "${RUSTC:?Set the installed compiler path with wasm32-unknown-unknown support}"
export CARGO_BUILD_JOBS=1
cargo build --offline --locked --jobs 1 --target wasm32-unknown-unknown --release --manifest-path "$HERE/Cargo.toml"
cp "$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/parallax_numerical_spike.wasm" "$HERE/../../demo/guidewire-fracture/wasm/renderer.wasm"
node -e 'const fs=require("node:fs"),crypto=require("node:crypto"),p=process.argv[1];const hash=crypto.createHash("sha256").update(fs.readFileSync(p+"/renderer.wasm")).digest("hex");fs.writeFileSync(p+"/identity.mjs","// Generated by the offline build; verified before instantiation.\nexport const WASM_SHA256="+JSON.stringify(hash)+";\n");' "$HERE/../../demo/guidewire-fracture/wasm"
